#!/usr/bin/env python3
"""Sticker packs: cut PNGs -> assets/stickers/<pack>/<slot>.webp, plus src/stickers/packs.gen.ts.

The art comes from chatgpt.com as two 4x3 sheets per pack (slots 1-12 and 13-24, see src/stickers/spec.json). Each
sheet is cut into squares named <pack>-<slot>.png (the cutter keeps every blob in the grid cell under its
centre). This script skips the slots listed in spec `drop` (the weakest 4 of 24), writes them as 384 px WebP with alpha (the source art is about 340 px a sticker) and
regenerates the TypeScript catalogue with static require()s so Metro bundles them.

    python3 -I scripts/make-stickers.py <dir of cut pngs>
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
CUT = sys.argv[1]
spec = json.load(open(os.path.join(APP, 'src/stickers/spec.json')))
out_ts = ['// Generated by scripts/make-stickers.py from src/stickers/spec.json. Do not edit by hand.',
          'export type Sticker = { id: string; pack: string; word: string; emoji: string; tags: string; src: number };',
          'export type Pack = { id: string; name: string; blurb: string; cover: number; stickers: Sticker[] };',
          '', 'export const PACKS: Pack[] = [']
total = 0
for p in spec['packs']:
    pid = p['id']
    keep = [n for n in range(1, len(p['stickers']) + 1) if n not in p.get('drop', [])]
    have = [n for n in keep if os.path.exists(f'{CUT}/{pid}-{n:02d}.png')]
    if not have:
        print(f'{pid}: no art yet, skipped'); continue
    d = os.path.join(APP, 'assets/stickers', pid); os.makedirs(d, exist_ok=True)
    for f in os.listdir(d):
        if f.endswith('.webp') and int(f[:2]) not in have: os.remove(os.path.join(d, f))
    rows = []
    for n in have:
        dst = f'{d}/{n:02d}.webp'
        subprocess.run(['cwebp', '-quiet', '-q', '80', '-alpha_q', '90', '-m', '6', '-resize', '384', '384', f'{CUT}/{pid}-{n:02d}.png', '-o', dst], check=True)
        word, emoji, tags = p['stickers'][n - 1]
        rows.append(f"    {{ id: '{pid}/{n:02d}', pack: '{pid}', word: {json.dumps(word, ensure_ascii=False)}, emoji: '{emoji}', tags: {json.dumps(tags)}, src: require('../../assets/stickers/{pid}/{n:02d}.webp') }},")
    cover = p.get('cover', have[0]); cover = cover if cover in have else have[0]
    out_ts.append(f"  {{ id: '{pid}', name: {json.dumps(p['name'])}, blurb: {json.dumps(p['blurb'])}, cover: require('../../assets/stickers/{pid}/{cover:02d}.webp'), stickers: [")
    out_ts += rows
    out_ts.append('  ] },')
    size = sum(os.path.getsize(f'{d}/{n:02d}.webp') for n in have)
    total += size
    print(f'{pid}: {len(have)} stickers, {size // 1024} KB')
out_ts.append('];')
open(os.path.join(APP, 'src/stickers/packs.gen.ts'), 'w').write('\n'.join(out_ts) + '\n')
print(f'total {total // 1024} KB')
